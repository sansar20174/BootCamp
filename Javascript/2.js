// Data Types in JavaScript

// 1. Primitive Data Types

// a. Number

var num = 30;
var num2 = 3.14;

console.log(num, typeof num, num2, typeof num2); 

// b. String

var nm1 = "Hello, World!";
console.log(nm1, typeof nm1);

// Note: Strings can be defined using single quotes, double quotes, or backticks (template literals).

var nm2 = 'Hello, JavaScript!';
var nm3 = `Hello, ES6!`;

console.log(nm2, typeof nm2, nm3, typeof nm3);

// c. Boolean

var isTrue = true;
var isFalse = false;

console.log(isTrue, typeof isTrue, isFalse, typeof isFalse);